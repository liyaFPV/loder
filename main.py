import requests
from bs4 import BeautifulSoup
import pandas as pd
import os
import time
from datetime import datetime
from tqdm import tqdm # Импортируем tqdm для прогресс-бара

def extract_table_from_url_to_excel(url, excel_writer, output_excel_name):
    """
    Извлекает HTML-таблицу с заданного URL и сохраняет ее в указанный Excel-файл.

    Args:
        url (str): URL страницы, с которой нужно извлечь таблицу.
        excel_writer (pd.ExcelWriter): Объект ExcelWriter для записи данных.
        output_excel_name (str): Имя выходного файла Excel.
    """
    max_retries = 4
    retry_delay_ms = 500 # 500 миллисекунд

    for attempt in range(max_retries):
        try:
            response = requests.get(url, timeout=15)
            response.raise_for_status()
            break  # Если запрос успешен, выходим из цикла повторных попыток
        except requests.exceptions.Timeout:
            print(f"[{os.path.basename(__file__)}] Ошибка: Таймаут при загрузке '{url}' (Попытка {attempt + 1}/{max_retries}).")
        except requests.exceptions.RequestException as e:
            print(f"[{os.path.basename(__file__)}] Ошибка при загрузке '{url}': {e} (Попытка {attempt + 1}/{max_retries}).")
        except Exception as e:
            print(f"[{os.path.basename(__file__)}] Неизвестная ошибка при загрузке '{url}': {e} (Попытка {attempt + 1}/{max_retries}).")

        if attempt < max_retries - 1:
            time.sleep(retry_delay_ms / 1000) # Преобразуем мс в секунды для time.sleep
        else:
            print(f"[{os.path.basename(__file__)}] Пропуск URL '{url}' после {max_retries} неудачных попыток.")
            return # Пропускаем URL после всех неудачных попыток

    # Если цикл завершился без break (все попытки провалились), то response не будет определен
    # Это уже обработано в блоке else выше, но для ясности добавим проверку
    if 'response' not in locals():
        return

    soup = BeautifulSoup(response.text, 'lxml')

    page_title_tag = soup.find('h1', class_='form-title')
    if page_title_tag:
        page_title = page_title_tag.get_text(strip=True)
    else:
        # Используем часть URL в качестве заголовка, если тег h1 не найден
        page_title = url.split('/')[-1].split('?')[0] or "Таблица"

    table = soup.find('table', id='filesTable')

    if not table:
        print(f"[{os.path.basename(__file__)}] Таблица с id='filesTable' не найдена на '{url}'.")
        return

    headers = []
    thead = table.find('thead')
    if thead:
        for th in thead.find_all('th'):
            if 'dtr-hidden' not in th.get('class', []):
                headers.append(th.get_text(separator=' ', strip=True))

    data = []
    tbody = table.find('tbody')
    if tbody:
        rows = tbody.find_all('tr')
        for row in rows:
            row_data = []
            cells = row.find_all(['td', 'th'])
            for cell in cells:
                if 'dtr-hidden' not in cell.get('class', []):
                    row_data.append(cell.get_text(strip=True))
            data.append(row_data)

    df = pd.DataFrame()
    if data:
        max_cols_in_data = max(len(row) for row in data)
        current_headers = list(headers)

        if len(current_headers) > max_cols_in_data:
            current_headers = current_headers[:max_cols_in_data]
        elif len(current_headers) < max_cols_in_data:
            current_headers.extend([f"Столбец {i+1}" for i in range(len(current_headers), max_cols_in_data)])
        
        df = pd.DataFrame(data, columns=current_headers)
    elif headers:
        df = pd.DataFrame(columns=headers)
    else:
        df = pd.DataFrame()

    try:
        # Очищаем имя листа от недопустимых символов и обрезаем до 31 символа
        sheet_name = page_title.replace('/', '_').replace('\\', '_').replace('*', '_').replace('[', '_').replace(']', '_').replace(':', '_').replace('?', '_')
        if len(sheet_name) > 31:
            sheet_name = sheet_name[:31]

        df.to_excel(excel_writer, sheet_name=sheet_name, index=False)
    except Exception as e:
        print(f"[{os.path.basename(__file__)}] Ошибка при сохранении в Excel: {e}")

if __name__ == "__main__":
    # Формируем имя файла Excel: data-дата-время
    timestamp = datetime.now().strftime("%Y-%m-%d-%H-%M-%S")
    output_file = f"data-{timestamp}.xlsx"

    try:
        with pd.ExcelWriter(output_file, engine='openpyxl') as writer:
            # Используем tqdm для отображения прогресс-бара
            for url in tqdm(target_urls, desc="Обработка страниц"):
                extract_table_from_url_to_excel(url, writer, output_file)
                time.sleep(1) # Небольшая задержка между запросами, чтобы не нагружать сервер
    except Exception as e:
        print(f"[{os.path.basename(__file__)}] Критическая ошибка при работе с ExcelWriter: {e}")
